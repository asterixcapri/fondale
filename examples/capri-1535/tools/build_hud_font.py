def glyph(pattern=(), accent=None):
    pen = TTGlyphPen(None)
    for row, pixels in enumerate(pattern):
        for column, pixel in enumerate(pixels):
            if pixel == "1":
                x, y = column * 100 + 40, (6 - row) * 100
                pen.moveTo((x, y)); pen.lineTo((x + 80, y)); pen.lineTo((x + 80, y + 80)); pen.lineTo((x, y + 80)); pen.closePath()
    accents = {"grave": ((1, 8), (2, 7)), "acute": ((3, 8), (2, 7))}
    for column, row in accents.get(accent, ()):
        x, y = column * 100 + 40, row * 100
        pen.moveTo((x, y)); pen.lineTo((x + 80, y)); pen.lineTo((x + 80, y + 80)); pen.lineTo((x, y + 80)); pen.closePath()
    return pen.glyph()


def main():
    glyphs = {".notdef": glyph(("11111", "10001", "10101", "10101", "10101", "10001", "11111")), "space": glyph()}
    cmap = {32: "space"}
    for character, pattern in PATTERNS.items():
        name = f"glyph{ord(character):04X}"
        glyphs[name] = glyph(pattern)
        cmap[ord(character)] = name
        if character.isalpha(): cmap[ord(character.lower())] = name
    for character, base, accent in (("à", "A", "grave"), ("è", "E", "grave"), ("é", "E", "acute"), ("ì", "I", "grave"), ("ò", "O", "grave"), ("ù", "U", "grave")):
        name = f"glyph{ord(character):04X}"
        glyphs[name] = glyph(PATTERNS[base], accent)
        cmap[ord(character)] = name
        cmap[ord(character.upper())] = name
    builder = FontBuilder(1000, isTTF=True)
    builder.setupGlyphOrder(list(glyphs))
    builder.setupCharacterMap(cmap)
    builder.setupGlyf(glyphs)
    builder.setupHorizontalMetrics({name: (600, 0) for name in glyphs})
    builder.setupHorizontalHeader(ascent=900, descent=-100)
    builder.setupOS2(sTypoAscender=900, sTypoDescender=-100, usWinAscent=900, usWinDescent=100)
    builder.setupNameTable({"familyName": "Capri Pixel", "styleName": "Regular", "uniqueFontIdentifier": "Fondale Capri Pixel 1.0", "fullName": "Capri Pixel", "psName": "CapriPixel-Regular", "version": "Version 1.0"})
    builder.setupPost()
    builder.setupMaxp()
    output = Path(__file__).parents[1] / "src/hud/capri-pixel.ttf"
    output.parent.mkdir(parents=True, exist_ok=True)
    builder.save(output)
    print(output)


if __name__ == "__main__":
    main()
